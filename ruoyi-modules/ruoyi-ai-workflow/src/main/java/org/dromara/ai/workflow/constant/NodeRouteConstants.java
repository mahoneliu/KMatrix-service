package org.dromara.ai.workflow.constant;

/**
 * 工作流节点路由 Key 常量
 * <p>
 * 统一管理条件节点、意图识别节点、循环节点等输出的路由 key 值，
 * 以及相关的分支前缀规则。
 *
 * @author Mahone
 */
public interface NodeRouteConstants {

    // =========================================================================
    // 循环节点（LOOP）路由
    // =========================================================================

    /** 循环继续路由 key */
    String LOOP_ROUTE_CONTINUE = "continue";

    /** 循环退出路由 key */
    String LOOP_ROUTE_EXIT = "exit";

    // =========================================================================
    // 条件节点（CONDITION）路由前缀
    // =========================================================================

    /** 条件分支 handleId 前缀（无 handleId 时自动生成） */
    String CONDITION_BRANCH_PREFIX = "condition-";

    /** 条件节点默认路由 key */
    String CONDITION_DEFAULT_ROUTE = "default";

    // =========================================================================
    // 意图识别节点（INTENT_CLASSIFIER）路由
    // =========================================================================

    /** 意图分支 handleId 前缀 */
    String INTENT_BRANCH_PREFIX = "intent-";

    /** 未匹配任何意图时的路由 key */
    String INTENT_ROUTE_ELSE = "else";

    // =========================================================================
    // 通用路由输出 key
    // =========================================================================

    /** 路由 key 的输出参数名 */
    String OUTPUT_ROUTE_KEY = "routeKey";
}
